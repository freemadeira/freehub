/** An OSM colour tag as a 24-bit RGB number: a CSS name, or #rgb / #rrggbb. */
export function colorOf(value: string | undefined): number | undefined {
  const text = (value ?? "")
    .trim()
    .toLowerCase()
    .replaceAll(/[\s_-]/gu, "");
  if (text in NAMED) {
    return NAMED[text];
  }
  const short = /^#?(?<r>[\da-f])(?<g>[\da-f])(?<b>[\da-f])$/u.exec(
    text
  )?.groups;
  if (short) {
    const { r = "", g = "", b = "" } = short;
    return Number.parseInt(`${r}${r}${g}${g}${b}${b}`, 16);
  }
  const long = /^#?(?<hex>[\da-f]{6})$/u.exec(text)?.groups;
  return long ? Number.parseInt(long.hex ?? "", 16) : undefined;
}
